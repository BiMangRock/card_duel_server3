-- schema.sql — 카드 결투 PostgreSQL(Supabase) 테이블
--  서버가 처음 DB 에 붙을 때 이 파일을 그대로 실행한다 (전부 IF NOT EXISTS 라 여러 번 실행해도 안전).
--  Supabase 대시보드의 SQL Editor 에 붙여 넣어 미리 만들어 둘 수도 있다.
--  시각(…_at)은 전부 epoch ms (BIGINT). 참/거짓은 예전 SQLite 와 같게 INTEGER 0/1.

CREATE TABLE IF NOT EXISTS users (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username    TEXT    NOT NULL,
  pw_hash     TEXT    NOT NULL,                       -- "scrypt$N$r$p$salt$hash"
  created_at  BIGINT  NOT NULL,
  last_login  BIGINT,
  is_admin    INTEGER NOT NULL DEFAULT 0,
  nickname    TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username ON users (lower(username));                              -- 대소문자 구분 없이 한 명만
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_nickname ON users (lower(nickname)) WHERE nickname IS NOT NULL;

CREATE TABLE IF NOT EXISTS sessions (
  token_hash  TEXT    PRIMARY KEY,                    -- 쿠키 토큰의 sha256
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at  BIGINT  NOT NULL,
  expires_at  BIGINT  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_user    ON sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions(expires_at);

CREATE TABLE IF NOT EXISTS wallets (
  user_id     INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  gold        INTEGER NOT NULL,
  pool        DOUBLE PRECISION NOT NULL,
  pool_day    TEXT    NOT NULL,
  bet         INTEGER NOT NULL DEFAULT 0,
  rev         INTEGER NOT NULL DEFAULT 1,
  updated_at  BIGINT  NOT NULL
);
CREATE TABLE IF NOT EXISTS decks (
  user_id     INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  deck_json   TEXT    NOT NULL,
  updated_at  BIGINT  NOT NULL
);
CREATE TABLE IF NOT EXISTS collection (
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  card_name   TEXT    NOT NULL,
  count       INTEGER NOT NULL,
  PRIMARY KEY (user_id, card_name)
);
CREATE TABLE IF NOT EXISTS collection_init (
  user_id     INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  granted_at  BIGINT  NOT NULL
);
CREATE TABLE IF NOT EXISTS shop_state (
  user_id       INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  since_epic    INTEGER NOT NULL DEFAULT 0,
