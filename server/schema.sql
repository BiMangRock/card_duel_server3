CREATE INDEX IF NOT EXISTS idx_pvp_pair_day   ON pvp_matches(p0, p1, day);
CREATE INDEX IF NOT EXISTS idx_pvp_match_id   ON pvp_matches(match_id);

CREATE TABLE IF NOT EXISTS app_config (
